function readStoredLanguage(): AppLanguage {
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "en" ? "en" : "fi";
  } catch {
    return "fi";
  }
}

let activeLanguage: AppLanguage = typeof window === "undefined" ? "fi" : readStoredLanguage();

export function t(source: string, language: AppLanguage = activeLanguage): string {
  if (language === "fi") return source;
  const leading = source.match(/^\s*/u)?.[0] ?? "";
  const trailing = source.match(/\s*$/u)?.[0] ?? "";
  const key = source.trim().replace(/\s+/gu, " ");
  return `${leading}${ENGLISH_TRANSLATIONS[key] ?? key}${trailing}`;
}

export function tTemplate(
  source: string,
  values: readonly unknown[],
  language: AppLanguage = activeLanguage,
): string {
  return t(source, language).replace(/\{\{(\d+)\}\}/gu, (_placeholder, index: string) => {
    const value: unknown = values[Number(index)];
    if (value === null || value === undefined) return "";
    if (
      typeof value === "string" ||
      typeof value === "number" ||
      typeof value === "boolean" ||
      typeof value === "bigint"
    ) {
      return String(value);
    }
    return "";
  });
}

export function getIntlLocale(language: AppLanguage = activeLanguage): string {
  return language === "en" ? "en-GB" : "fi-FI";
}

export function tOptions<T extends { readonly value: string; readonly label: string }>(
  options: readonly T[],
): readonly T[] {
  return options.map((option) => ({ ...option, label: t(option.label) }));
}

interface LanguageContextValue {
  readonly language: AppLanguage;
  readonly setLanguage: (language: AppLanguage) => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({
  children,
}: {
  readonly children: ReactNode;
}): React.JSX.Element {
  const [language, setLanguageState] = useState<AppLanguage>(() => readStoredLanguage());

  useEffect(() => {
    document.documentElement.lang = language;
    activeLanguage = language;
    const description = document.querySelector('meta[name="description"]');
    description?.setAttribute("content", t("LifeOS — local-first arjenhallinnan selainapp."));
  }, [language]);

  const setLanguage = useCallback((nextLanguage: AppLanguage): void => {
    activeLanguage = nextLanguage;
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch {
      // The current session still switches language when browser storage is unavailable.
    }
    setLanguageState(nextLanguage);
  }, []);

  const value = useMemo<LanguageContextValue>(
    () => ({ language, setLanguage }),
    [language, setLanguage],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (context === null) {
    throw new Error("useLanguage must be used inside LanguageProvider.");
  }
  return context;
}
